import type { DecisionGraphSnapshot, DecisionEdgeInput, DecisionNodeInput, OptionPath } from '../domain/decisionGraph';

function node(
  id: string,
  role: DecisionNodeInput['role'],
  label: string,
  detail: string,
  epistemicStatus: DecisionNodeInput['epistemicStatus'],
  basis: string,
  optionPath?: OptionPath,
): DecisionNodeInput {
  return {
    id,
    role,
    label,
    detail,
    epistemicStatus,
    basis,
    sourceRefIds: [],
    optionPath,
  };
}

function edge(
  id: string,
  sourceId: string,
  targetId: string,
  type: DecisionEdgeInput['type'],
  rationale: string,
): DecisionEdgeInput {
  return { id, sourceId, targetId, type, rationale };
}

